// Builds src/lib/geo/ogun-map.ts from geoBoundaries NGA ADM2 (CC BY 4.0).
// Usage: node scripts/build-map.mjs <path-to-geoBoundaries-NGA-ADM2_simplified.geojson>
import fs from "node:fs";
import { geoMercator, geoPath, geoArea, geoContains, geoCentroid } from "d3-geo";
import { topology } from "topojson-server";
import { merge } from "topojson-client";

const src = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const ZONES = [
  { id: "abs", name: "Abeokuta South", code: "ABSZPO", lgas: ["Abeokuta South"], office: "Ake, Abeokuta", at: [3.352, 7.155] },
  { id: "abn", name: "Abeokuta North", code: "ABNZPO", lgas: ["Abeokuta North", "Odeda"], office: "Akomoje, Abeokuta", at: [3.27, 7.25] },
  { id: "ifo", name: "Ifo", code: "IFZPO", lgas: ["Ifo", "Ewekoro"], office: "Ifo", at: [3.2, 6.82] },
  { id: "atn", name: "Atan", code: "ATZPO", lgas: ["Ado Odo/Ota"], office: "Atan, Ota", at: [3.06, 6.68] },
  { id: "mow", name: "Mowe", code: "MWZPO", lgas: ["Obafemi Owode"], office: "Mowe", at: [3.43, 6.81] },
  { id: "sag", name: "Sagamu", code: "SGZPO", lgas: ["Shagamu"], office: "Sagamu", at: [3.65, 6.84] },
  { id: "ikn", name: "Ikenne", code: "IKZPO", lgas: ["Ikenne", "Remo North"], office: "Ikenne", at: [3.71, 6.87] },
  { id: "ijo", name: "Ijebu-Ode", code: "IJZPO", lgas: ["Ijebu Ode", "Ijebu North East"], office: "Ijebu-Ode", at: [3.92, 6.82] },
  { id: "ago", name: "Ago-Iwoye", code: "AGZPO", lgas: ["Ijebu North"], office: "Ago-Iwoye", at: [3.91, 6.94] },
  { id: "odo", name: "Odogbolu", code: "ODZPO", lgas: ["Odogbolu"], office: "Odogbolu", at: [3.77, 6.83] },
  { id: "ije", name: "Ijebu East / Waterside", code: "IEZPO", lgas: ["Ijebu East", "Ogun Waterside"], office: "Ogbere", at: [4.2, 6.8] },
  { id: "yen", name: "Yewa North", code: "YNZPO", lgas: ["Yewa North", "Imeko Afon"], office: "Ayetoro", at: [3.03, 7.23] },
  { id: "ila", name: "Ilaro", code: "ILZPO", lgas: ["Yewa South", "Ipokia"], office: "Ilaro", at: [3.02, 6.89] },
];
const lgaZone = Object.fromEntries(ZONES.flatMap((z) => z.lgas.map((l) => [l, z.id])));
const feats = src.features.filter((f) => lgaZone[f.properties.shapeName] && !(f.properties.shapeName === "Ado" ));
if (feats.length !== 20) throw new Error("expected 20 LGAs, got " + feats.length);

// d3 wants clockwise rings; flip any feature whose area exceeds a hemisphere.
const rewind = (g) => {
  const flip = (poly) => poly.map((r) => [...r].reverse());
  if (geoArea(g) > 2 * Math.PI) {
    if (g.type === "Polygon") g.coordinates = flip(g.coordinates);
    else g.coordinates = g.coordinates.map(flip);
  }
  return g;
};
feats.forEach((f) => rewind(f.geometry));
const fc = { type: "FeatureCollection", features: feats };

const W = 800;
const proj = geoMercator().fitWidth(W - 40, fc);
const path0 = geoPath(proj);
const [[x0, y0], [x1, y1]] = path0.bounds(fc);
proj.translate([proj.translate()[0] - x0 + 20, proj.translate()[1] - y0 + 20]);
const H = Math.ceil(y1 - y0 + 40);
const path = geoPath(proj).digits(1);

const topo = topology({ l: fc }, 1e5);
const geoms = topo.objects.l.geometries;
const zoneOut = ZONES.map((z) => {
  const mine = geoms.filter((g, i) => lgaZone[feats[i].properties.shapeName] === z.id);
  const m = rewind(merge(topo, mine));
  const f = { type: "Feature", geometry: m, properties: {} };
  let at = z.at;
  if (!geoContains(f, at)) { console.warn("office outside zone, using centroid:", z.name); at = geoCentroid(f); }
  const [ox, oy] = proj(at);
  const [cx, cy] = path.centroid(f);
  const [[bx0, by0], [bx1, by1]] = path.bounds(f);
  return { id: z.id, name: z.name, code: z.code, office: z.office, lgas: z.lgas, d: path(f),
    officeXY: [+ox.toFixed(1), +oy.toFixed(1)], label: [+cx.toFixed(1), +cy.toFixed(1)],
    bbox: [bx0, by0, bx1 - bx0, by1 - by0].map((n) => +n.toFixed(1)) };
});
const state = path(rewind(merge(topo, geoms)));
const lgas = feats.map((f) => ({ name: f.properties.shapeName, zone: lgaZone[f.properties.shapeName], d: path(f) }));

const out = `// GENERATED by scripts/build-map.mjs — do not edit.
// Boundaries: geoBoundaries (wmgeolab) NGA ADM2, CC BY 4.0. Zone groupings are illustrative.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const STATE_PATH = ${JSON.stringify(state)};
export const ZONE_SHAPES = ${JSON.stringify(zoneOut, null, 0)} as const;
export const LGA_SHAPES = ${JSON.stringify(lgas)} as const;
`;
fs.mkdirSync("src/lib/geo", { recursive: true });
fs.writeFileSync("src/lib/geo/ogun-map.ts", out);
console.log("ok", W, H, (out.length / 1024).toFixed(0) + "KB");
